pub const HID_PAUSE: u16 = 0x48;
pub const HID_NUM_LOCK: u16 = 0x53;

/// The scancode to send for a HID usage.
pub fn scancode(hid: u16) -> Option<(u16, bool)> {
    match hid {
        HID_NUM_LOCK => Some((0x45, true)), // as Windows reports it, despite set 1
        HID_PAUSE => Some((0x45, false)),
        _ => PAIRS.iter().find(|p| p.0 == hid).map(|p| (p.1, p.2)),
    }
}

/// The HID usage of a key as a low-level keyboard hook reports it. Pause and Num Lock share
/// scancode 0x45 there, so the virtual key tells them apart.
pub fn hid(scan: u16, extended: bool, vk: u16) -> Option<u16> {
    match vk {
        0x13 => return Some(HID_PAUSE),    // VK_PAUSE
        0x90 => return Some(HID_NUM_LOCK), // VK_NUMLOCK
        0x2C => return Some(0x46),         // VK_SNAPSHOT: Print Screen
        _ => {}
    }
    PAIRS.iter().find(|p| p.1 == scan && p.2 == extended).map(|p| p.0)
}

/// Media keys: consumer usages <-> virtual keys.
const MEDIA: &[(u16, u16)] = &[
    (0xE9, 0xAF), // volume up
    (0xEA, 0xAE), // volume down
    (0xE2, 0xAD), // mute
    (0xCD, 0xB3), // play/pause
    (0xB5, 0xB0), // next track
    (0xB6, 0xB1), // previous track
    (0xB7, 0xB2), // stop
];

pub fn media_vk(usage: u16) -> Option<u16> {
    MEDIA.iter().find(|m| m.0 == usage).map(|m| m.1)
}

pub fn media_usage(vk: u16) -> Option<u16> {
    MEDIA.iter().find(|m| m.1 == vk).map(|m| m.0)
}

/// HID keyboard-page volume keys (sent by Mac keyboards) as media virtual keys.
pub fn keyboard_volume_vk(hid: u16) -> Option<u16> {
    match hid {
        0x7F => Some(0xAD), // mute
        0x80 => Some(0xAF), // volume up
        0x81 => Some(0xAE), // volume down
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips() {
        for &(hid_usage, scan, ext) in PAIRS {
            assert_eq!(hid(scan, ext, 0), Some(hid_usage), "{hid_usage:#x}");
            assert_eq!(scancode(hid_usage), Some((scan, ext)));
        }
    }
}
