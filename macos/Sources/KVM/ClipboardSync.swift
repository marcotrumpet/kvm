import AppKit

/// Shares the clipboard with the peer while connected: whatever is copied on one machine
/// can be pasted on the other. Main thread only, except where noted.
///
/// Payload (shared with the other platforms, see docs/protocol.md): `count: u16 BE`, then
/// per entry `type_len: u16 BE | MIME type | len: u32 BE | bytes`.
///
/// Files copied in Finder are sent right away (up to a size limit) into a cache on the
/// peer, which offers them as promised file URLs: pasting waits for the transfer if it is
/// still running, then Finder copies them from the cache.
final class ClipboardSync: NSObject, NSPasteboardItemDataProvider {
    private let core: Core
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// The change count of the clipboard as we last set it from the peer, so it isn't
    /// sent straight back.
    private var setByPeer: Int?
    var connected = false
    /// Send files copied in Finder (off for remote controls, which can't paste them).
    var shareFiles = true
    /// Main thread; something worth telling the user (e.g. a copy too big to share).
    var onNotice: ((String) -> Void)?

    // Files copied on the peer and offered for pasting here.
    private var offered: [ObjectIdentifier: (transfer: UInt64, url: URL)] = [:]
    /// Per incoming clipboard transfer: files arrived, files expected (known once the
    /// first one arrives), failure. Written on the core thread, waited on from main.
    private var arrivals: [UInt64: (arrived: Int, count: Int?, failed: String?)] = [:]
    private let arrivalsChanged = NSCondition()
    private static let pasteWaitLimit: TimeInterval = 120

    private static let filesType = "application/x-kvm-files"
    private static let filesTooLargeType = "application/x-kvm-files-too-large"
    private static let mimeToType: [(mime: String, type: NSPasteboard.PasteboardType)] = [
        ("text/plain", .string), ("text/html", .html), ("text/rtf", .rtf), ("image/png", .png),
    ]
    /// Markers apps (password managers, mostly) put on contents that must not be shared.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping",
    ]
    private static let maxBytes = 30 * 1024 * 1024

    init(core: Core) {
        self.core = core
        super.init()
        try? FileManager.default.removeItem(at: Settings.clipboardCacheDirectory)
        Core.setClipboardDirectory(Settings.clipboardCacheDirectory)
    }

    func start() {
        // The pasteboard has no change notification; polling the change count is cheap.
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard connected, Settings.shareClipboard, pasteboard.changeCount != setByPeer,
              let item = pasteboard.pasteboardItems?.first,
              Set(item.types.map(\.rawValue)).isDisjoint(with: ClipboardSync.privateTypes) else { return }
        let files = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !files.isEmpty {
            if shareFiles, Settings.clipboardFileLimit > 0 { shareCopiedFiles(files, changeCount: pasteboard.changeCount) }
        } else if let payload = ClipboardSync.encodeContents(item) {
            core.sendClipboard(payload)
        }
    }

    // MARK: Copying here

    private func shareCopiedFiles(_ urls: [URL], changeCount: Int) {
        // Sizing a big folder can take a while; don't hold up the main thread.
        DispatchQueue.global(qos: .userInitiated).async { [self] in
            let size = urls.reduce(Int64(0)) { $0 + ClipboardSync.size(of: $1) }
            DispatchQueue.main.async { [self] in
                guard NSPasteboard.general.changeCount == changeCount, connected else { return } // copied again since
                let names = urls.map(\.lastPathComponent)
                guard size <= Settings.clipboardFileLimit else {
                    let json = try? JSONSerialization.data(withJSONObject: ["names": names, "bytes": size])
                    core.sendClipboard(ClipboardSync.encode([(ClipboardSync.filesTooLargeType, json ?? Data())]))
                    Log.info("copied files not shared: \(size) bytes is over the limit")
                    return
                }
                guard let transfer = core.sendFiles(urls, clipboard: true) else { return }
                let json = try? JSONSerialization.data(withJSONObject: ["transfer": String(transfer), "names": names])
                core.sendClipboard(ClipboardSync.encode([
                    (ClipboardSync.filesType, json ?? Data()),
                    ("text/plain", Data(names.joined(separator: "\n").utf8)),
                ]))
                Log.info("sharing \(urls.count) copied item(s), \(size) bytes")
            }
        }
    }

    private static func size(of url: URL) -> Int64 {
        let keys: [URLResourceKey] = [.isRegularFileKey, .fileSizeKey]
        guard let values = try? url.resourceValues(forKeys: Set(keys)) else { return 0 }
        if values.isRegularFile == true { return Int64(values.fileSize ?? 0) }
        var total: Int64 = 0
        let walker = FileManager.default.enumerator(at: url, includingPropertiesForKeys: keys)
        while let file = walker?.nextObject() as? URL {
            if let v = try? file.resourceValues(forKeys: Set(keys)), v.isRegularFile == true {
                total += Int64(v.fileSize ?? 0)
            }
        }
        return total
    }

    // MARK: Copied on the peer

    /// Contents copied on the peer.
    func received(_ payload: Data) {
        guard Settings.shareClipboard, let entries = ClipboardSync.decode(payload), !entries.isEmpty else { return }
        if let files = entries.first(where: { $0.0 == ClipboardSync.filesType }) {
            offerFiles(files.1)
            return
        }
        if let tooLarge = entries.first(where: { $0.0 == ClipboardSync.filesTooLargeType }),
           let info = try? JSONSerialization.jsonObject(with: tooLarge.1) as? [String: Any] {
            let names = info["names"] as? [String] ?? []
            let bytes = ByteCountFormatter.string(fromByteCount: info["bytes"] as? Int64 ?? 0, countStyle: .file)
            let what = names.count == 1 ? names[0] : "\(names.count) items"
            onNotice?("\(what) (\(bytes)) too large to paste here: use Send Files")
            return
        }
        let item = NSPasteboardItem()
        for (mime, data) in entries {
            if let type = ClipboardSync.mimeToType.first(where: { $0.mime == mime })?.type {
                item.setData(data, forType: type)
            }
        }
        write([item])
    }

    private func offerFiles(_ json: Data) {
        guard let info = try? JSONSerialization.jsonObject(with: json) as? [String: Any],
              let transfer = (info["transfer"] as? String).flatMap(UInt64.init),
              let names = info["names"] as? [String], !names.isEmpty else { return }
        removeCachedFiles(except: transfer)
        let folder = Settings.clipboardCacheDirectory.appendingPathComponent(String(transfer), isDirectory: true)
        offered.removeAll()
        let items = names.map { name -> NSPasteboardItem in
            let item = NSPasteboardItem()
            item.setDataProvider(self, forTypes: [.fileURL])
            item.setString(name, forType: .string)
            offered[ObjectIdentifier(item)] = (transfer, folder.appendingPathComponent(name))
            return item
        }
        write(items)
    }

    private func write(_ items: [NSPasteboardItem]) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects(items)
        setByPeer = pasteboard.changeCount
        lastChange = pasteboard.changeCount
    }

    /// Only the newest copy can still be pasted; earlier cached copies go.
    private func removeCachedFiles(except transfer: UInt64) {
        let cache = Settings.clipboardCacheDirectory
        let entries = (try? FileManager.default.contentsOfDirectory(at: cache, includingPropertiesForKeys: nil)) ?? []
        for entry in entries where entry.lastPathComponent != String(transfer) {
            try? FileManager.default.removeItem(at: entry)
        }
        arrivalsChanged.lock()
        arrivals = arrivals.filter { $0.key == transfer }
        arrivalsChanged.unlock()
    }

    /// Something is pasting a promised file: hand over its URL once it has arrived.
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .fileURL, let (transfer, url) = offered[ObjectIdentifier(item)] else { return }
        if let error = waitForFiles(transfer) {
            Log.warn("pasting \(url.lastPathComponent): \(error)")
            onNotice?("Couldn't paste \(url.lastPathComponent): \(error)")
            return
        }
        item.setString(url.absoluteString, forType: .fileURL)
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}

    /// Blocks until every file of `transfer` has arrived; returns an error otherwise.
    private func waitForFiles(_ transfer: UInt64) -> String? {
        let deadline = Date().addingTimeInterval(ClipboardSync.pasteWaitLimit)
        arrivalsChanged.lock()
        defer { arrivalsChanged.unlock() }
        while true {
            let state = arrivals[transfer]
            if let failed = state?.failed { return failed }
            if let state, let count = state.count, state.arrived >= count { return nil }
            if !arrivalsChanged.wait(until: deadline) { return "still copying from the other computer" }
        }
    }

    /// Core thread.
    func fileArrived(transfer: UInt64, count: Int) {
        arrivalsChanged.lock()
        var state = arrivals[transfer] ?? (0, nil, nil)
        state.arrived += 1
        state.count = count
        arrivals[transfer] = state
        arrivalsChanged.broadcast()
        arrivalsChanged.unlock()
    }

    /// Core thread.
    func fileFailed(transfer: UInt64, message: String) {
        arrivalsChanged.lock()
        var state = arrivals[transfer] ?? (0, nil, nil)
        state.failed = message
        arrivals[transfer] = state
        arrivalsChanged.broadcast()
        arrivalsChanged.unlock()
    }

    // MARK: Encoding

    private static func encodeContents(_ item: NSPasteboardItem) -> Data? {
        var entries: [(String, Data)] = []
        for (mime, type) in mimeToType where type != .png {
            if let data = item.data(forType: type) { entries.append((mime, data)) }
        }
        if let png = item.data(forType: .png) {
            entries.append(("image/png", png))
        } else if let tiff = item.data(forType: .tiff),
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            entries.append(("image/png", png)) // TIFF converted: smaller, and portable
        }
        guard !entries.isEmpty else { return nil }
        let size = entries.reduce(0) { $0 + $1.1.count }
        guard size <= maxBytes else {
            Log.warn("clipboard not shared: \(size) bytes is too large")
            return nil
        }
        return encode(entries)
    }

    private static func encode(_ entries: [(String, Data)]) -> Data {
        var out = Data()
        func put16(_ v: Int) { out.append(contentsOf: [UInt8(v >> 8 & 0xFF), UInt8(v & 0xFF)]) }
        func put32(_ v: Int) { out.append(contentsOf: [24, 16, 8, 0].map { UInt8(v >> $0 & 0xFF) }) }
        put16(entries.count)
        for (mime, data) in entries {
            let name = Data(mime.utf8)
            put16(name.count)
            out.append(name)
            put32(data.count)
            out.append(data)
        }
        return out
    }

    private static func decode(_ payload: Data) -> [(String, Data)]? {
        let bytes = [UInt8](payload)
        var offset = 0
        func take(_ n: Int) -> ArraySlice<UInt8>? {
            guard offset + n <= bytes.count else { return nil }
            defer { offset += n }
            return bytes[offset..<offset + n]
        }
        func int(_ n: Int) -> Int? { take(n).map { $0.reduce(0) { $0 << 8 | Int($1) } } }
        guard let count = int(2) else { return nil }
        var entries: [(String, Data)] = []
        for _ in 0..<count {
            guard let nameLen = int(2), let name = take(nameLen), let len = int(4), let data = take(len),
                  let mime = String(bytes: name, encoding: .utf8) else { return nil }
            entries.append((mime, Data(data)))
        }
        return entries
    }
}
