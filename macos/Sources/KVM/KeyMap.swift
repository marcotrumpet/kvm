    private static let vkToHid = Dictionary(uniqueKeysWithValues: pairs.map { ($0.vk, $0.hid) })
    private static let hidToVk = Dictionary(uniqueKeysWithValues: pairs.map { ($0.hid, $0.vk) })

    static func hid(fromVK vk: UInt16) -> UInt16? { vkToHid[vk] }
    static func vk(fromHID hid: UInt16) -> UInt16? { hidToVk[hid] }

    static let capsLockVK: UInt16 = 0x39

    /// A modifier key: its device-dependent flag bit (left/right distinct) and generic flag.
    struct Modifier {
        let deviceMask: UInt64
        let flag: CGEventFlags
    }

    static let modifiers: [UInt16: Modifier] = [
        0x3B: Modifier(deviceMask: 0x0000_0001, flag: .maskControl),   // left control
        0x3E: Modifier(deviceMask: 0x0000_2000, flag: .maskControl),   // right control
        0x38: Modifier(deviceMask: 0x0000_0002, flag: .maskShift),     // left shift
        0x3C: Modifier(deviceMask: 0x0000_0004, flag: .maskShift),     // right shift
        0x37: Modifier(deviceMask: 0x0000_0008, flag: .maskCommand),   // left command
        0x36: Modifier(deviceMask: 0x0000_0010, flag: .maskCommand),   // right command
        0x3A: Modifier(deviceMask: 0x0000_0020, flag: .maskAlternate), // left option
        0x3D: Modifier(deviceMask: 0x0000_0040, flag: .maskAlternate), // right option
    ]

    /// Flags a real keyboard puts on a key regardless of modifiers. System shortcuts are
    /// matched including these: Ctrl+← only switches desktops if the arrow carries the
    /// numeric-pad and fn flags, like a hardware arrow key does.
    static func intrinsicFlags(vk: UInt16) -> CGEventFlags {
        switch vk {
        case 0x7B...0x7E: // arrows
            return [.maskNumericPad, .maskSecondaryFn]
        case 0x41, 0x43, 0x45, 0x47, 0x4B, 0x4C, 0x4E, 0x51, 0x52...0x59, 0x5B, 0x5C: // keypad
            return .maskNumericPad
        case 0x60...0x65, 0x67, 0x69...0x6B, 0x6D, 0x6F, 0x71...0x79, 0x40, 0x4F, 0x50, 0x5A:
            return .maskSecondaryFn // F-keys, help, home, end, page up/down, forward delete
        default:
            return []
        }
    }

    /// Modifier keys currently held according to `flags`.
    static func heldModifiers(in flags: CGEventFlags) -> Set<UInt16> {
        Set(modifiers.filter { flags.rawValue & $0.value.deviceMask != 0 }.keys)
    }

    /// The flags an event should carry when `held` modifier keys are down.
    static func flags(forHeld held: Set<UInt16>) -> CGEventFlags {
        var flags = CGEventFlags()
        for vk in held {
            guard let m = modifiers[vk] else { continue }
            flags.insert(m.flag)
            flags.insert(CGEventFlags(rawValue: m.deviceMask))
        }
        return flags
    }
}
